"""Build deterministic, version-specific CC:Tweaked datapacks using stdlib only."""
from __future__ import annotations
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
from zipfile import ZipFile, ZipInfo, ZIP_DEFLATED

ROOT = Path(__file__).resolve().parents[1]
MODERN_FORMAT = 82

def load_targets():
    targets = json.loads((ROOT / 'datapack/targets.json').read_text())
    for version, target in targets.items():
        if not re.fullmatch(r'\d+\.\d+(?:\.\d+)?', version):
            raise ValueError(f'Invalid Minecraft version: {version}')
        value = target['format']
        if len(value) != 2 or any(type(n) is not int or n < 0 for n in value):
            raise ValueError(f'Invalid format for {version}')
        if target.get('inherits') and targets[target['inherits']]['format'] != value:
            raise ValueError(f'Inherited format mismatch: {version}')
    return targets

def metadata(version, target, lpm_version):
    major, minor = target['format']
    pack = {'description': f'LPM {lpm_version} for Minecraft {version} / CC:Tweaked'}
    if major < MODERN_FORMAT:
        pack['pack_format'] = major
    else:
        pack['min_format'] = [major, minor]
        pack['max_format'] = [major, minor]
    return {'pack': pack}

def as_json(value):
    return (json.dumps(value, indent=2, ensure_ascii=False) + '\n').encode()

def write_zip(path, files):
    with ZipFile(path, 'w', compression=ZIP_DEFLATED, compresslevel=9) as archive:
        for name, body in sorted(files.items()):
            info = ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = ZIP_DEFLATED
            info.create_system = 3
            info.external_attr = 0o100644 << 16
            archive.writestr(info, body, compress_type=ZIP_DEFLATED, compresslevel=9)

def build(output, versions=None, commit=None):
    output = Path(output)
    targets = load_targets()
    selected = list(versions) if versions else list(targets)
    if len(set(selected)) != len(selected) or any(v not in targets for v in selected):
        raise ValueError('Unknown or duplicate Minecraft version')
    if commit is None:
        commit = os.environ.get('GITHUB_SHA') or subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
    if not re.fullmatch(r'[0-9a-fA-F]{40}', commit):
        raise ValueError('Source commit must be a full Git SHA')
    commit = commit.lower()
    bundle = (ROOT / 'lpm.lua').read_bytes()
    match = re.match(rb'-- LPM (\d+\.\d+\.\d+)\. Generated by tools/build\.py\.\n', bundle)
    if not match:
        raise ValueError('Rebuild the standalone LPM bundle before packaging')
    lpm_version = match.group(1).decode()
    base = {f'data/computercraft/lua/{p.relative_to(ROOT / "datapack").as_posix()}': p.read_bytes()
            for p in (ROOT / 'datapack/rom').rglob('*.lua')}
    base['data/computercraft/lua/rom/lpm/lpm.lua'] = bundle
    if any(name != name.lower() for name in base):
        raise ValueError('Datapack resource paths must be lowercase')
    output.mkdir(parents=True, exist_ok=True)
    manifest = {'schema': 1, 'repository': 'p4ncak3s-R0ck/LPM', 'commit': commit,
                'lpm_version': lpm_version, 'targets': []}
    for version in selected:
        target = targets[version]
        name = f'lpm-datapack-mc-{version}.zip'
        provenance = {'minecraft': version, 'pack_format': target['format'],
                      'lpm_version': lpm_version, 'commit': commit,
                      'bundle_sha256': hashlib.sha256(bundle).hexdigest()}
        files = dict(base)
        files['pack.mcmeta'] = as_json(metadata(version, target, lpm_version))
        files['lpm-build.json'] = as_json(provenance)
        files['readme.txt'] = (f'LPM datapack for Minecraft {version}\n'
            'Requires a compatible CC:Tweaked installation.\n'
            'Place this ZIP unchanged in <world>/datapacks/ on each server. Enable it with /reload (or restart the server), then reboot existing computers.\n'
            'At boot, LPM is copied once to /bin/lpm.lua; existing local installs and startup files are preserved.\n'
            'Run lpm self-update for updates. Installing LPM does not require HTTP; package downloads do.\n'
            'Use only the ZIP for your Minecraft version. This pack does not install CC:Tweaked itself.\n'
            f'Source commit: {commit}\n').encode()
        write_zip(output / name, files)
        manifest['targets'].append({'minecraft': version, 'format': target['format'], 'asset': name})
    (output / 'lpm.lua').write_bytes(bundle)
    (output / 'build-manifest.json').write_bytes(as_json(manifest))
    names = [x['asset'] for x in manifest['targets']] + ['lpm.lua', 'build-manifest.json']
    checksums = ''.join(f'{hashlib.sha256((output / n).read_bytes()).hexdigest()}  {n}\n' for n in sorted(names))
    (output / 'SHA256SUMS.txt').write_text(checksums)
    notes = ['# LPM nightly', '', f'Source commit: `{commit}`', '',
             'Download the ZIP matching your Minecraft version and place it unchanged in `<world>/datapacks/` on each server.',
             'Enable the pack with `/reload` (or restart the server), then reboot existing CC:Tweaked computers. New computers install LPM on their first boot.',
             'The boot installer preserves existing writable copies, so `lpm self-update` remains available. Requires CC:Tweaked for the selected Minecraft version.', '',
             '| Minecraft | Datapack asset |', '| --- | --- |']
    notes += [f'| {x["minecraft"]} | `{x["asset"]}` |' for x in manifest['targets']]
    notes += ['', 'This is a mutable prerelease. Server startup and filesystem behavior were tested in a CC:Tweaked Lua simulation; no Minecraft server was launched in CI.', '']
    (output / 'RELEASE_NOTES.md').write_text('\n'.join(notes))
    return manifest

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'dist')
    parser.add_argument('--versions', nargs='+', help='Local builds only: select known target versions')
    parser.add_argument('--commit')
    args = parser.parse_args()
    result = build(args.output, args.versions, args.commit)
    print(f'Built {len(result["targets"])} datapacks in {args.output}')
